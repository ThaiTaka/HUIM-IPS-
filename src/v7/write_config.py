"""Write the full configuration of the selected V7 model (read back from the code and the result files).

    BAOCAO_V7/cau_hinh/v7_config.json   and   configs/v7.yaml
"""
from __future__ import annotations

import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy
import sklearn

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from v7.common import GF, OUT, PROJECT_ROOT, TRAIN_CSV, VALID_CSV, git_rev, sha256_file  # noqa: E402
from v7.run_dev import CFG, VARIANTS  # noqa: E402


def main() -> None:
    dev = json.load(open(OUT / "dev" / "C_rel_absL3.json"))
    test = json.load(open(OUT / "test_summary.json"))["C_rel_absL3"]
    a = json.load(open(OUT / "V7A_dev.json"))["adaptT"]
    cfg = {
        "selected_model": "C_rel_absL3 (V7-C2)",
        "selection_rule": "lowest out-of-fold dev mean error on informative queries among the declared variants; validationData not used for selection",
        "dataset": {"train": "ujiindoorloc/UJIndoorLoc/trainingData.csv", "train_sha256": sha256_file(TRAIN_CSV),
                    "test": "ujiindoorloc/UJIndoorLoc/validationData.csv", "test_sha256": sha256_file(VALID_CSV),
                    "ground_factor_m_per_coordinate_unit": GF, "n_wap": 520, "cells": 933},
        "folds": {"scheme": "GroupKFold", "n_splits": 6, "group": "PHONEID (16 training phones)"},
        "hui": {"algorithm": "EFIM (src/huim/efim.py, exact; verified against brute force)", "theta_pct": 20.0, "external_utility": 1.0,
                "per_cell_budget": {"time_s": 10, "max_huis": 10000, "escalation": 1.25},
                "models": {"rank": "rank utility, items = AP", "rank_L3": "rank utility, items = (AP, level of 3)",
                           "abs": "absolute-strength utility", "rel": "strength relative to the strongest AP (40 dB window)",
                           "abs_L3": "absolute-strength utility, items = (AP, level of 3)"},
                "final_hui_counts": {"rank": 3238416, "rank_L3": 1031786, "abs": 3062754, "rel": 3197333, "abs_L3": 2371262}},
        "candidates": {"k": 30, "floor_rule": "floor whose 20 best cells have the highest mean smoothed HUI score (kf=20)",
                       "score": "S = P(gamma=2,tau=20) * V^3, Gaussian smoothing sigma=3 m within the floor"},
        "features": {"v6_columns": 33, "extra_blocks": list(VARIANTS["C_rel_absL3"]), "block_columns": 8,
                     "transform": "each feature + (x - max over candidates), min-max within the query, rank; then signed log; z-score"},
        "scorer": {"type": "shared MLP with pooled-candidate branch", **{k: v for k, v in CFG.items()},
                   "loss": "mean(0.766126 * ||sum_i w_i c_i - x_true||), w = softmax(s)", "optimiser": "Adam (b1 .9, b2 .999), batch 256",
                   "ensemble": "one member per training fold; member i early-stops on fold i and is fitted on the others; scores averaged, then softmax",
                   "seed": 0},
        "v7a_fusion_rule_declared": {"params_in_sample_on_dev": a["in_sample_best"]["params"], "nested_dev_informative_mean": a["nested_dev_informative_mean"]},
        "results": {"dev_oof_informative_mean_m": dev["mean_inf"], "dev_oof_all_mean_m": dev["mean_all"],
                    "test_mean_m": test["mean"], "test_median_m": test["median"], "test_p90_m": test["p90"],
                    "test_floor_accuracy": test["floor_accuracy"], "test_building_accuracy": test["building_accuracy"]},
        "software": {"python": platform.python_version(), "numpy": np.__version__, "scipy": scipy.__version__,
                     "scikit_learn": sklearn.__version__, "git_rev_of_code": git_rev()},
    }
    p = PROJECT_ROOT / "BAOCAO_V7" / "cau_hinh"
    p.mkdir(parents=True, exist_ok=True)
    json.dump(cfg, open(p / "v7_config.json", "w"), ensure_ascii=False, indent=1)

    def yml(o, ind=0):
        out = []
        for k, v in o.items():
            if isinstance(v, dict):
                out.append(" " * ind + f"{k}:")
                out += yml(v, ind + 2)
            else:
                out.append(" " * ind + f"{k}: {json.dumps(v, ensure_ascii=False)}")
        return out
    (PROJECT_ROOT / "configs" / "v7.yaml").write_text("# HUIM-IPS V7 - selected model (generated by src/v7/write_config.py; do not edit by hand)\n" + "\n".join(yml(cfg)) + "\n",
                                                      encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
